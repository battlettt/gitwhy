def _e(s):
    return html.escape(str(s), quote=True)


def _sha(sha, span=None):
    label = sha[:8] + (" " + span if span else "")
    return '<span class="sha" title="%s">%s</span>' % (_e(sha), _e(label))


def _page(title, body):
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            "<title>%s</title><style>%s</style></head><body><main>%s"
            "<footer>Generated by GitWhy from local git history on %s. No network, no hosted services.</footer>"
            "</main></body></html>\n") % (_e(title), _CSS, body, time.strftime("%Y-%m-%d %H:%M"))


def story_html(story, top=10):
    t = story.target
    o = story.origin
    c = o.commit
    h = story.heat
    b = []
    b.append("<h1>Why does %s exist?</h1>" % _e(t.label))
    b.append('<p class="sub">Read from %s at %s%s.</p>' % (
        _e(t.repo), _e(t.rev), (", function " + _e(t.function)) if t.function else ""))

    b.append("<h2>Heat</h2><div class=\"card\">")
    b.append('<span class="verdict %s">%s</span> <span>%s</span>' % (h.verdict, h.verdict, _e(h.reason)))
    b.append("<ul>%s</ul>" % "".join("<li>%s</li>" % _e(e) for e in h.evidence))
    if story.references:
        b.append("<p>References at %s:</p><ul>%s</ul>" % (_e(t.rev), "".join(
            "<li><code>%s:%d</code> %s</li>" % (_e(p), ln, _e(txt[:80])) for p, ln, txt in story.references[:8])))
    b.append('<p class="sub">Rules: HOT if changed within %d days or %d+ commits in a year; STALE if untouched '
             'for %d+ days and referenced fewer than 2 times; STABLE otherwise. Range judged: %s.</p></div>'
             % (RECENT_DAYS, BUSY_COMMITS, STALE_DAYS, _e(t.span)))

    b.append("<h2>Story</h2><div class=\"card\">")
    b.append("<p>Introduced in %s by <strong>%s</strong> &lt;%s&gt; on %s, as %s of <code>%s</code>.</p>" % (
        _sha(c.sha, o.span), _e(c.author), _e(c.email), _e(c.iso[:16]), _e(o.span), _e(o.path)))
    b.append('<pre class="msg">%s</pre>' % _e(c.message or "(empty message)"))
    current = story.current_shas
    if current and (current[0] != c.sha or len(current) > 1):
        b.append("<p>Current text written by: %s</p>" % ", ".join(
            _sha(s, "(%d line%s)" % (n, "" if n == 1 else "s")) for s, n in
            ((s, sum(1 for x in story.blame if x.sha == s)) for s in current)))
    lo = max(1, t.start - story.context)
    hi = min(len(t.lines), t.end + story.context)
    rows = []
    for n in range(lo, hi + 1):
        hit = " hit" if t.start <= n <= t.end else ""
        rows.append('<span class="code-line%s"><span class="ln">%d</span>%s</span>' % (hit, n, _e(t.lines[n - 1])))
    b.append("<pre>%s</pre></div>" % "".join(rows))

    b.append("<h2>Timeline</h2><div class=\"card wrap\"><table><tr><th>Date</th><th>Commit</th><th>Author</th>"
             "<th>Change</th><th>Message</th></tr>")
    for i, e in enumerate(story.timeline):
        cc = e.commit
        what = "introduced" if i == 0 else "+%d &minus;%d" % (e.added, e.removed)
        b.append("<tr><td>%s</td><td>%s<br><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td></tr>" % (
            _e(cc.date), _sha(cc.sha, e.span), _e(e.path), _e(cc.author), what, _e(cc.subject)))
    b.append("</table></div>")

    if story.renames:
        b.append("<h2>Renames</h2>")
        for r in story.renames:
            warn = " warn" if r.kind in ("cutoff", "possible-cutoff", "shallow") else ""
            b.append('<div class="card%s">%s %s</div>' % (warn, _sha(r.sha), _e(r.text)))

    total = len(story.timeline)
    b.append("<h2>Company</h2><div class=\"card wrap\">")
    if story.company:
        b.append("<p>Files that changed in the same %d commit%s as %s.</p><table><tr><th>File</th><th>Together</th>"
                 "<th></th><th>Commits</th></tr>" % (total, "" if total == 1 else "s", _e(t.span)))
        for comp in story.company[:top]:
            b.append('<tr><td><code>%s</code></td><td>%d/%d</td><td style="width:30%%"><div class="bar" '
                     'style="width:%d%%"></div></td><td>%s</td></tr>' % (
                         _e(comp.path), comp.count, total, round(comp.share(total) * 100),
                         " ".join(_sha(s) for s in comp.shas[:6])))
        b.append("</table>")
        if len(story.company) > top:
            b.append('<p class="sub">%d more not shown.</p>' % (len(story.company) - top))
    else:
        b.append("<p>Every commit that touched %s changed only this file.</p>" % _e(t.span))
    b.append("</div>")
    return _page("GitWhy: " + t.label, "".join(b))


def filemap_html(fm):
    t = fm.target
    b = ["<h1>Heat map of %s</h1>" % _e(t.path),
         '<p class="sub">%d lines at %s, %d regions. CHURN %d%%, NEW %d%%, SETTLED %d%%, OLD %d%% of lines.</p>' % (
             (len(t.lines), _e(t.rev), len(fm.regions)) + tuple(
                 round(fm.share(x) * 100) for x in ("CHURN", "NEW", "SETTLED", "OLD")))]
    b.append('<div class="card wrap"><table><tr><th>Lines</th><th>Tag</th><th>Commits</th><th>Age</th>'
             "<th>Last change</th><th>Subject</th></tr>")
    for r in fm.regions:
        n = r.newest
        b.append('<tr><td>%d-%d</td><td><span class="verdict %s">%s</span></td><td>%d</td><td>%d days</td>'
                 "<td>%s</td><td>%s</td></tr>" % (
                     r.start, r.end, r.tag, r.tag, max(len(r.commits), len(r.shas)), r.days_since_last,
                     _sha(n.sha, r.span), _e(n.summary)))
    b.append("</table></div>")
    b.append('<p class="sub">CHURN: touched by 4+ commits. NEW: every line under 90 days old. OLD: untouched '
             "for a year or more. SETTLED: everything else.</p>")
    return _page("GitWhy heat map: " + t.path, "".join(b))
